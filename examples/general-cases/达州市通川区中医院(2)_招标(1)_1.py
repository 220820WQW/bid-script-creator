    def get_list(self, params: dict):
        ret_list = []

        resp = auto_request(url=params['url'], headers=HEADERS, cookies=COOKIES, json=params['data'])
        if 400 <= resp.status_code <= 599:
            return ret_list

        rows = resp.json().get('data').get('records')

        for row in rows:
            id = row.get('id')
            url = f"https://dzstcqzyy.cn/expertIntroduction/detail/{id}/%E6%97%A0?name="

            title = row.get('title')
            pubTime = row.get('publishTime')
            ret_list.append({'url': url, 'title': title, 'pubTime': pubTime, 'id': id})

        return ret_list

    def get_content(self, params: dict):
        url = "https://www.dzstcqzyy.cn/gfwz-api/website/artcle/info"
        payload = {
            "id": params['id']
        }
        resp = auto_request(url=url, headers=HEADERS, cookies=COOKIES, json=payload)
        if 400 <= resp.status_code <= 599:
            return None

        obj = resp.json().get('data')
        content = obj.get('content')
        content = handle_str.completion_url(str(content), params['url'])

        return {"title": params['title'], "pubTime": params['pubTime'], "url": params['url'], "content": content}


